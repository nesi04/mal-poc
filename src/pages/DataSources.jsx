import { useEffect, useState } from 'react'
import { useData } from '../lib/data.jsx'
import { OriginTag } from '../components/Tags.jsx'

function normalize(v) {
  let h = v.trim().toLowerCase().replace(/\[\.\]/g, '.')
  h = h.replace(/^[a-z]+:\/\//, '')
  return h.split('/')[0].split('?')[0].split(':')[0]
}

export default function DataSources() {
  const { data } = useData()
  const ds = data.data_sources
  const pub = ds.public
  const [hosts, setHosts] = useState(null)
  const [q, setQ] = useState('')

  useEffect(() => {
    fetch(`${import.meta.env.BASE_URL}data/intel_public.json`).then((r) => r.json()).then(setHosts).catch(() => setHosts([]))
  }, [])

  const host = normalize(q)
  let result = null
  if (host) {
    if (ds.synthetic_intel.includes(host)) result = 'Found in the synthetic known-bad list. Rule R1 would block this inline.'
    else if (hosts && hosts.includes(host)) result = 'Found in the public list. Rule R1 would block this inline.'
    else result = 'Not in the threat-intel table.'
  }
  const counts = Object.entries(pub.class_counts || {}).sort((a, b) => b[1] - a[1])

  return (
    <>
      <h1>Data sources</h1>
      <p className="lede">
        Almost everything on this dashboard is generated by the project. One optional public dataset can extend the known-bad
        lookup. This page shows what is loaded and where each kind of data comes from.
      </p>

      <h2>What is loaded</h2>
      <div className="table-wrap">
        <table>
          <thead><tr><th scope="col">Data</th><th scope="col">Origin</th><th scope="col">Status</th><th scope="col">Used for</th></tr></thead>
          <tbody>
            <tr>
              <th scope="row">Journeys, events, alerts, triage, containment</th>
              <td><OriginTag origin="synthetic" /></td>
              <td>{data.meta.journeys} journeys, {ds.journey_domains} domains</td>
              <td>Everything the red team and blue team do</td>
            </tr>
            <tr>
              <th scope="row">Public malicious URL list</th>
              <td><OriginTag origin="public" /></td>
              <td>{pub.loaded ? <span className="status-done">Loaded</span> : <span className="status-open">Not loaded</span>}
                {pub.loaded && <span className="sub">{pub.rows_read.toLocaleString()} rows read, {pub.hostnames_used} hostnames used</span>}</td>
              <td>Extends the known-bad lookup used by rule R1</td>
            </tr>
            <tr>
              <th scope="row">Metrics, findings, choke points</th>
              <td><span className="tag tag-origin">Calculated</span></td>
              <td>Computed on every pipeline run</td>
              <td>Scorecard, findings register, choke-point analysis</td>
            </tr>
          </tbody>
        </table>
      </div>

      <h2>Threat-intel table</h2>
      <p>
        Rule R1 checks every destination against {ds.intel_total} entries: {ds.intel_synthetic} synthetic and {ds.intel_public} from the public list.
      </p>

      {pub.loaded ? (
        <>
          <h3>Public dataset</h3>
          <p className="small">
            <OriginTag origin="public" /> File {pub.file}, layout {pub.schema}. Up to {pub.hostname_limit} phishing and malware hostnames are kept.
          </p>
          <div className="table-wrap">
            <table>
              <thead><tr><th scope="col">Class</th><th scope="col">Rows</th></tr></thead>
              <tbody>{counts.map(([cls, n]) => <tr key={cls}><th scope="row">{cls}</th><td className="num">{n.toLocaleString()}</td></tr>)}</tbody>
            </table>
          </div>
          {ds.sample_defanged.length > 0 && (
            <p className="small">Sample hostnames, defanged so they are not clickable: {ds.sample_defanged.join(', ')}</p>
          )}
        </>
      ) : (
        <div className="panel">
          <h3>No public dataset loaded yet</h3>
          <p>The dashboard works without it. To add one:</p>
          <ol>
            <li>Download a malicious-URL dataset, for example the Kaggle "Malicious URLs Dataset" (kaggle.com/datasets/sid321axn/malicious-urls-dataset).</li>
            <li>Save it as <code>pipeline/data/public/malicious_urls.csv</code>. Two layouts are recognised: columns <code>url,type</code>, or the PhiUSIIL layout <code>URL,label</code> (1 legitimate, 0 phishing).</li>
            <li>Run <code>python pipeline/run_pipeline.py</code> and reload this page. A "Public data" label appears in the banner.</li>
          </ol>
          {pub.notes.length > 0 && <p className="muted small">{pub.notes.join(' ')}</p>}
        </div>
      )}

      <h3>Check a domain against the table</h3>
      <div className="lookup">
        <label htmlFor="lookup-q">Domain or URL</label>
        <input id="lookup-q" type="text" value={q} onChange={(e) => setQ(e.target.value)} placeholder="secure-docs-verify.test" autoComplete="off" spellCheck="false" />
      </div>
      <p aria-live="polite" className="lookup-result">{result}</p>
      <p className="muted small">Try {ds.synthetic_intel[0]}. {ds.note}</p>

      <h3>Data labels</h3>
      <dl className="defs">
        {Object.entries(data.meta.data_origin_legend).map(([k, v]) => (
          <div key={k}><dt>{k}</dt><dd>{v}</dd></div>
        ))}
      </dl>
    </>
  )
}
